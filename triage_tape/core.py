"""Parsing and rendering primitives for Triage Tape."""

from __future__ import annotations

from dataclasses import dataclass
from datetime import date
import json
import re

PRIORITY = {"p0": 0, "p1": 1, "p2": 2, "p3": 3}
LINE = re.compile(
    r"^\s*\[(?P<priority>P[0-3])\]\s*(?P<state>open|blocked|watch|done)\s*"
    r"-\s*(?P<body>.+?)\s*$",
    re.IGNORECASE,
)
OWNER = re.compile(r"\s+@(?P<owner>[\w.-]+)(?=\s|$)")
DUE = re.compile(r"\s+due:(?P<due>\d{4}-\d{2}-\d{2})(?=\s|$)")


@dataclass(frozen=True)
class Item:
    priority: str
    state: str
    summary: str
    owner: str | None = None
    due: str | None = None

    @property
    def is_open(self) -> bool:
        return self.state != "done"

    @property
    def identity(self) -> str:
        """A stable, human-readable key for comparing two handoffs."""
        return " ".join(self.summary.casefold().split())


def parse_notes(text: str) -> tuple[list[Item], list[str]]:
    """Return recognized items and actionable formatting warnings."""
    items: list[Item] = []
    warnings: list[str] = []
    for number, raw in enumerate(text.splitlines(), 1):
        if not raw.strip() or raw.lstrip().startswith("#"):
            continue
        match = LINE.match(raw)
        if not match:
            warnings.append(f"Line {number}: couldn't read item")
            continue
        data = match.groupdict()
        body = data["body"]
        owner_match = OWNER.search(body)
        due_match = DUE.search(body)
        owner = owner_match.group("owner") if owner_match else None
        due = due_match.group("due") if due_match else None
        summary = DUE.sub("", OWNER.sub("", body)).strip()
        items.append(Item(data["priority"].lower(), data["state"].lower(), summary, owner, due))
    return items, warnings


def build_handoff(
    items: list[Item],
    title: str,
    today: date | None = None,
    previous_items: list[Item] | None = None,
) -> str:
    """Render a decision-ready Markdown handoff."""
    today = today or date.today()
    active = sorted((item for item in items if item.is_open), key=lambda item: (PRIORITY[item.priority], item.due or "9999-99-99"))
    done = [item for item in items if not item.is_open]
    blocked = [item for item in active if item.state == "blocked"]
    unowned = [item for item in active if not item.owner]
    overdue = [item for item in active if item.due and item.due < today.isoformat()]
    lines = [f"# {title}", "", f"_Prepared {today.isoformat()} · {len(active)} active items_", ""]
    lines += ["## At a glance", "", f"- **{len(blocked)}** blocked · **{len(overdue)}** overdue · **{len(unowned)}** without an owner", ""]
    lines += ["## Open work", ""]
    if active:
        for item in active:
            owner = f" — @{item.owner}" if item.owner else " — **owner needed**"
            due = f" · due {item.due}" if item.due else ""
            flag = " ⚠" if item.state == "blocked" else ""
            lines.append(f"- **{item.priority.upper()} · {item.state}**{flag}: {item.summary}{owner}{due}")
    else:
        lines.append("- No active work. Nice handoff.")
    if blocked:
        lines += ["", "## Blockers to resolve", ""]
        lines += [f"- {item.summary} ({'@' + item.owner if item.owner else 'owner needed'})" for item in blocked]
    if previous_items is not None:
        previous_active = {item.identity: item for item in previous_items if item.is_open}
        current_active = {item.identity: item for item in active}
        current_by_identity = {item.identity: item for item in items}
        new_items = [item for item in active if item.identity not in previous_active]
        no_longer_active = [
            item for key, item in previous_active.items() if key not in current_active
        ]
        lines += ["", "## Since the previous handoff", ""]
        if new_items:
            lines.append("### New work")
            lines += [f"- **{item.priority.upper()}**: {item.summary}" for item in new_items]
        if no_longer_active:
            if new_items:
                lines.append("")
            lines.append("### No longer active")
            for item in no_longer_active:
                current = current_by_identity.get(item.identity)
                status = "completed" if current and not current.is_open else "removed from this log"
                lines.append(f"- {item.summary} — {status}")
        if not new_items and not no_longer_active:
            lines.append("- No active-work changes since the previous handoff.")
    if done:
        lines += ["", "## Closed since last handoff", ""]
        lines += [f"- {item.summary}" for item in done]
    lines += ["", "---", "_Generated by [Triage Tape](https://github.com/Chandan-14r/triage-tape)._", ""]
    return "\n".join(lines)


def build_handoff_json(
    items: list[Item],
    title: str,
    today: date | None = None,
    previous_items: list[Item] | None = None,
) -> str:
    """Render the handoff as stable, automation-friendly JSON."""
    today = today or date.today()
    active = sorted(
        (item for item in items if item.is_open),
        key=lambda item: (PRIORITY[item.priority], item.due or "9999-99-99"),
    )
    blocked = [item for item in active if item.state == "blocked"]
    unowned = [item for item in active if not item.owner]
    overdue = [item for item in active if item.due and item.due < today.isoformat()]

    def as_dict(item: Item) -> dict[str, str | None]:
        return {
            "priority": item.priority.upper(),
            "state": item.state,
            "summary": item.summary,
            "owner": item.owner,
            "due": item.due,
        }

    payload: dict[str, object] = {
        "title": title,
        "prepared_on": today.isoformat(),
        "summary": {
            "active": len(active),
            "blocked": len(blocked),
            "overdue": len(overdue),
            "unowned": len(unowned),
            "closed": len(items) - len(active),
        },
        "active_items": [as_dict(item) for item in active],
        "closed_items": [as_dict(item) for item in items if not item.is_open],
    }
    if previous_items is not None:
        previous_active = {item.identity: item for item in previous_items if item.is_open}
        current_active = {item.identity: item for item in active}
        current_by_identity = {item.identity: item for item in items}
        no_longer_active = []
        for key, item in previous_active.items():
            if key not in current_active:
                current = current_by_identity.get(key)
                no_longer_active.append(
                    {**as_dict(item), "outcome": "completed" if current and not current.is_open else "removed"}
                )
        payload["changes_since_previous"] = {
            "new_active": [as_dict(item) for item in active if item.identity not in previous_active],
            "no_longer_active": no_longer_active,
        }
    return json.dumps(payload, indent=2) + "\n"
